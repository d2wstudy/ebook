#!/usr/bin/env node

import { readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, extname, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import { existsSync, mkdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bookConfigPath = resolve(rootDir, 'book.config.ts')
const wranglerConfigPath = resolve(rootDir, 'worker', 'wrangler.jsonc')
const outputPath = resolve(rootDir, 'worker', 'generated', 'document-ids.ts')

const bookConfig = readFileSync(bookConfigPath, 'utf8')
const wranglerConfig = parseJsonc(readFileSync(wranglerConfigPath, 'utf8'))
const contentDir = readQuotedProperty(bookConfig, 'contentDir', 'content')
const base = normalizeBase(wranglerConfig.vars?.DOCUMENT_PATH_PREFIX || '/')
const contentRoot = resolve(rootDir, contentDir)
const slugs = new Set()

for (const languageEntry of readdirSync(contentRoot, { withFileTypes: true })) {
  if (!languageEntry.isDirectory() || !/^[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]+)*$/.test(languageEntry.name)) continue
  const languageRoot = resolve(contentRoot, languageEntry.name)
  for (const file of markdownFiles(languageRoot)) {
    const raw = readFileSync(file, 'utf8').replace(/^\uFEFF/, '')
    const match = raw.match(/^---\s*\r?\n([\s\S]*?)\r?\n---\s*(?:\r?\n|$)/)
    const metadata = match ? parse(match[1]) : {}
    const relativeFile = relative(languageRoot, file).split(sep).join('/')
    const inferredSlug = relativeFile.replace(/^chapters\//, '').replace(/\.md$/i, '')
    const slug = typeof metadata?.slug === 'string' && metadata.slug.trim()
      ? metadata.slug.trim()
      : inferredSlug
    if (!/^[A-Za-z0-9][A-Za-z0-9/_-]*$/.test(slug) || slug.split('/').includes('..')) {
      throw new Error(`无效页面 slug：${slug}（${file}）`)
    }
    slugs.add(slug)
  }
}

const documentIds = [
  `${base}index.html`,
  ...[...slugs].map(slug => `${base}chapters/${slug}.html`),
].sort()
const content = [
  '// Generated by scripts/generate-worker-documents.mjs. Do not edit manually.',
  'export const VALID_DOCUMENT_IDS = [',
  ...documentIds.map(id => `  ${JSON.stringify(id)},`),
  '] as const',
  '',
].join('\n')

writeIfChanged(outputPath, content)
console.log(`已生成 ${relative(rootDir, outputPath)}（${documentIds.length} 个页面）`)

function markdownFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) return markdownFiles(path)
    return extname(entry.name).toLowerCase() === '.md' && statSync(path).isFile() ? [path] : []
  })
}

function readQuotedProperty(source, property, fallback) {
  const match = source.match(new RegExp(`\\b${property}\\s*:\\s*'([^']*)'`))
  return match?.[1] || fallback
}

function normalizeBase(value) {
  const clean = `/${String(value || '').trim().replace(/^\/+|\/+$/g, '')}/`
  return clean === '//' ? '/' : clean
}

function parseJsonc(source) {
  return JSON.parse(source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, ''))
}

function writeIfChanged(filePath, content) {
  if (existsSync(filePath) && readFileSync(filePath, 'utf8') === content) return
  mkdirSync(dirname(filePath), { recursive: true })
  const temporaryPath = `${filePath}.${process.pid}.tmp`
  writeFileSync(temporaryPath, content)
  try {
    renameSync(temporaryPath, filePath)
  } catch {
    if (existsSync(filePath)) unlinkSync(filePath)
    renameSync(temporaryPath, filePath)
  }
}
